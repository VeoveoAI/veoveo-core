-- Request cancellation. An unowned Task has no worker to observe the request, so it
-- is cancelled at once.
UPDATE tasks.task
SET status = CASE WHEN owner_instance IS NULL THEN 'cancelled' ELSE 'cancel_requested' END,
    status_message = CASE WHEN owner_instance IS NULL THEN 'Cancelled' ELSE 'Cancelling' END,
    cancel_requested_at = now(),
    completed_at = CASE WHEN owner_instance IS NULL THEN now() END
WHERE id = $1 AND server = $2 AND status IN ('queued', 'running', 'waiting')
RETURNING
    id AS "id: TaskId",
    server,
    tenant,
    owner_tenant,
    owner_principal,
    owner_kind AS "owner_kind: PrincipalKind",
    owner_issuer,
    owner_subject,
    profile,
    data_labels,
    work_context,
    authority AS "authority: Json<InvocationAuthority>",
    task_type,
    recovery_class AS "recovery_class: RecoveryClass",
    input,
    idempotency_key,
    ttl_ms,
    poll_interval_ms,
    status AS "status: TaskStatus",
    status_message,
    progress,
    result,
    result_uri,
    error_code,
    error_message,
    error_details,
    owner_instance,
    revision,
    retention_pins,
    created_at,
    updated_at,
    started_at,
    cancel_requested_at,
    completed_at,
    retention_expires_at
